"""Explicit installed observation loader; never invoked by install or the GUI.

Caller prepares the owned journal and exact generated bytes, owns the endpoint
and qualified receiver, and runs this in its independently watched process.
arm() starts the installed rollback worker and requires its actual pipe reply.
apply() changes only the recorded hook; reload() is separate so the caller can
capture post-write sources and prepare its receive loop first. No retry, PF,
new configuration, process signal or implicit worker termination is provided.
"""
import json
import os
from pathlib import Path
import select
import subprocess
import sys
import time

from .bootidentity import capture
from .plainsetup import exchange_owned
from .hookplan import digest
from .hooktrial import HookTrialFile,deadline_status
from .processwatch import ProcessLifetimeWatch
from .reloadrequest import ReloadRequest
from .runtimecontrol import RuntimeControl
from .sourceaudit import SourceAudit,SourceSpec
from .trialworker import validate_context


class ObservationTrial:
    def __init__(self,context,*,overlay,control,resolver_watch,persistent=False):
        if type(persistent) is not bool:raise ValueError('explicit persistent hook mode required')
        self.persistent=persistent;self.follow_watch=None;self.follow_deadline=None
        self.context=validate_context(context)
        if not sys.platform.startswith('freebsd') or os.geteuid()!=0 or context['coordinator_pid']!=os.getpid():
            raise ValueError('explicit native root coordinator process required')
        if (not isinstance(control,RuntimeControl) or control.address!='127.0.0.1'
            or control.port!=context['control_port'] or not isinstance(resolver_watch,ProcessLifetimeWatch)
            or resolver_watch.pid!=context['resolver_pid']):
            raise ValueError('matching enrolled resolver and control service required')
        import manage
        self.root,self.data=Path(context['root']),Path(context['data'])
        if self.root!=Path(__file__).resolve().parents[1]:raise ValueError('exact installed coordinator required')
        manage.verify(self.root,self.data)
        owned=manage.inspect_trial_directory(self.root,self.data)
        if owned is None or owned['phase']!='prepared' or owned['pending_file']:raise ValueError('new owned prepared trial required')
        self.journal=HookTrialFile(self.data/manage.TRIAL_DIRECTORY,expected_uid=0)
        try:
            self.value=self.journal.read()['checkpoint'];self.plan=self.value['plan']
            if persistent and self.plan['duration_seconds'] is not None:raise ValueError('persistent hook requires an indefinite plan')
            if type(overlay) is not bytes or not 0<len(overlay)<=1048576 or digest(overlay)!=self.plan['overlay']['installed_sha256']:
                raise ValueError('exact prepared overlay required')
            if capture()['boot_id']!=self.plan['boot_id']:raise ValueError('prepared boot changed')
            if any(Path(self.plan[key]['path']).parent!=Path(context['control_directory']) for key in ('hook','config')):
                raise ValueError('explicit inspected resolver directory required')
            self.specs=[SourceSpec(**(self.plan[key]|{'modes':tuple(self.plan[key]['modes'])})) for key in ('hook','config')]
            self.ancestors=tuple(dict.fromkeys((0,context['control_uid'],*[spec.uid for spec in self.specs])))
        except Exception:self.journal.close();raise
        self.overlay,self.control,self.resolver=overlay,control,resolver_watch
        self.child=self.worker_watch=None;self.readiness=self.result=None
        self.state='prepared';self.load_open=None;self.reason=None;self.pipe=bytearray();self.stop_attempted=False

    def _message(self,timeout):
        deadline=time.monotonic()+timeout
        while b'\n' not in self.pipe:
            remaining=max(0,deadline-time.monotonic())
            if not select.select([self.child.stdout],[],[],remaining)[0]:return None
            chunk=os.read(self.child.stdout.fileno(),8193-len(self.pipe))
            if not chunk:raise ValueError('rollback worker pipe ended')
            self.pipe.extend(chunk)
            if len(self.pipe)>8192:raise ValueError('rollback response exceeds bound')
        raw,_,remainder=self.pipe.partition(b'\n');self.pipe=bytearray(remainder)
        value=json.loads(raw)
        if type(value) is not dict:raise ValueError('complete worker response required')
        return value

    def _guard(self,phase):
        if self.state!=phase:raise ValueError('trial operation already attempted or out of order')
        if self.worker_watch is None or not self.worker_watch.alive() or self.child.poll() is not None or not self.resolver.alive():
            raise ValueError('enrolled worker or resolver lifetime ended')
        value=self.journal.read()['checkpoint']
        if value['plan']!=self.plan or value['status']['phase']!='armed' or value['status']['worker']!=self.readiness['worker']:
            raise ValueError('armed journal changed')
        decision=deadline_status(value,boot_id=self.plan['boot_id'],now=time.monotonic(),utc_now=time.time())
        if decision['decision']!='waiting' or decision['remaining_seconds'] is not None and decision['remaining_seconds']<2:
            raise ValueError('trial has insufficient time remaining')

    def arm(self):
        if self.state!='prepared':raise ValueError('trial cannot be rearmed')
        self.state='arming'
        try:
            self.child=subprocess.Popen([sys.executable,'-B','-m','dnsalias.trialworker',
                '--run-persistent-observation-hook' if self.persistent else '--run-prepared-observation-trial'],
                stdin=subprocess.PIPE,stdout=subprocess.PIPE,stderr=subprocess.DEVNULL,cwd=self.root,bufsize=0,
                start_new_session=True)
            self.worker_watch=ProcessLifetimeWatch(self.child.pid)
            raw=(json.dumps(self.context,separators=(',',':'))+'\n').encode()
            if len(raw)>8192:raise ValueError('worker context exceeds pipe bound')
            if self.child.stdin.write(raw)!=len(raw):raise ValueError('incomplete private context write')
            ready=self._message(3)
            if (ready is None or set(ready)!={'ready','trial_id','worker'} or ready['ready'] is not True
                or ready['trial_id']!=self.plan['trial_id'] or type(ready['worker']) is not dict
                or ready['worker'].get('pid')!=self.child.pid):raise ValueError('independent durable readiness missing')
            self.readiness=ready;self.state='armed';self._guard('armed')
            return dict(ready)
        except Exception as exc:
            self.state='uncertain';self.reason='arm_failed:'+type(exc).__name__;raise

    def apply(self):
        try:
            self._guard('armed');self.state='applying'
            with SourceAudit(self.specs,ancestor_uids=self.ancestors) as audit:
                if audit.hashes['resolver_config']!=self.plan['config_sha256']:raise ValueError('resolver configuration changed')
                result=exchange_owned(self.data,audit,self.plan['overlay'],overlay=self.overlay)
            self.state='applied';self._guard('applied')
            return result
        except Exception as exc:
            self.state='uncertain';self.reason='apply_failed:'+type(exc).__name__;raise

    def reload(self):
        try:
            self._guard('applied')
            with SourceAudit(self.specs,ancestor_uids=self.ancestors) as audit:
                if (audit.hashes['resolver_config']!=self.plan['config_sha256']
                    or audit.hashes['selected_hook']!=self.plan['overlay']['installed_sha256']):
                    raise ValueError('prepared overlay or configuration changed')
            self._guard('applied');self.state='reloading';self.load_open=time.monotonic()
            result=ReloadRequest(self.control,self.resolver).send()
            self.state='loaded';self._guard('loaded')
            return {'load_open':self.load_open,'request':result,'generation_qualified':False}
        except Exception as exc:
            self.state='uncertain';self.reason='reload_failed:'+type(exc).__name__;raise

    def request_stop(self):
        """Send one fixed command; only the normal worker result proves undo."""
        if self.stop_attempted:raise ValueError('stop already attempted; inspect the original outcome')
        if self.state not in ('armed','applied','loaded'):raise ValueError('qualified running trial required')
        value=self.journal.read()['checkpoint']
        if value['plan']!=self.plan or value['status']['worker']!=self.readiness['worker']:
            raise ValueError('stop target journal changed')
        phase=value['status']['phase']
        if phase in ('restoring','restored','complete'):
            self.stop_attempted=True
            return {'requested':False,'restoration_verified':False,'automatic_retry':False,'reason':'rollback_already_started'}
        if (phase!='armed' or not self.worker_watch.alive() or self.child.poll() is not None
            or not self.resolver.alive()):raise ValueError('stop target lifetime or phase changed')
        decision=deadline_status(value,boot_id=self.plan['boot_id'],now=time.monotonic(),utc_now=time.time())
        if decision['decision']=='inspect':raise ValueError('stop target clock unqualified')
        self.stop_attempted=True
        if decision['decision']=='restore_due':
            return {'requested':False,'restoration_verified':False,'automatic_retry':False,'reason':'original_deadline_due'}
        if self.child.stdin.write(b'stop\n')!=5:raise OSError('stop request outcome unavailable')
        return {'requested':True,'restoration_verified':False,'automatic_retry':False}

    def request_follow(self,resolver_watch):
        """Request independent producer discovery; no PID is sent on the pipe.

        poll_follow is nonblocking so the caller keeps expiring leases and
        pulsing its independent membership watchdog during worker validation.
        """
        if (not self.persistent or self.state!='loaded' or self.follow_watch is not None
            or self.stop_attempted or not isinstance(resolver_watch,ProcessLifetimeWatch)
            or resolver_watch.pid==self.resolver.pid or not resolver_watch.alive()
            or self.resolver.alive() or self.resolver.state!='exited'):
            raise ValueError('confirmed old producer exit and fresh live replacement required')
        self._persistent_guard()
        self.state='following';self.follow_watch=resolver_watch;self.follow_deadline=time.monotonic()+2
        try:
            if self.child.stdin.write(b'follow\n')!=7:raise OSError('follow request outcome unavailable')
            return {'requested':True,'replacement_qualified':False,'automatic_retry':False}
        except Exception:self.state='uncertain';raise

    def _persistent_guard(self):
        if self.worker_watch is None or not self.worker_watch.alive() or self.child.poll() is not None:
            raise ValueError('original hook worker lifetime ended')
        saved=self.journal.read()['checkpoint']
        if (saved['plan']!=self.plan or saved['status']['phase']!='armed'
            or saved['status']['worker']!=self.readiness['worker']):raise ValueError('live owned hook journal changed')

    def poll_follow(self):
        if self.state!='following' or self.follow_watch is None:raise ValueError('one pending follow required')
        try:
            self._persistent_guard()
            value=self._message(0)
            if value is None:
                if time.monotonic()>=self.follow_deadline:raise TimeoutError('replacement qualification outcome unavailable')
                return None
            if (value!={'followed':True,'resolver_pid':self.follow_watch.pid,'hook_restored':False,'reload_requested':False}
                or not self.follow_watch.alive()):raise ValueError('replacement readiness refused')
            self.resolver=self.follow_watch;self.follow_watch=None;self.follow_deadline=None;self.state='loaded'
            return value
        except Exception:self.state='uncertain';raise

    def poll(self):
        """Nonblocking result receipt; journal and actual behavior remain evidence."""
        if self.child is None:return None
        try:
            if self.result is not None:return self._exited_result()
            value=self._message(0)
            if value is not None:
                if (value.get('journal_phase') not in ('complete','conflict','uncertain')
                    or not isinstance(value.get('controller'),dict)
                    or value['controller'].get('state')!=value['journal_phase']):
                    raise ValueError('worker ended without matching terminal rollback report')
                saved=self.journal.read();record=saved['checkpoint']
                if (record['plan']!=self.plan or record['status']['worker']!=self.readiness['worker']
                    or record['status']['phase']!=value['journal_phase']):raise ValueError('worker outcome does not match journal')
                self.result=value;self.completed_digest=saved['file_sha256'];self.state=value['journal_phase']
                return self._exited_result()
            return None
        except Exception as exc:
            self.state='uncertain';self.reason='worker_result_failed:'+type(exc).__name__;raise

    def _exited_result(self):
        """A terminal message is not child exit; keep its journal until both."""
        code=self.child.poll()
        if code is None:return None
        if self.worker_watch.alive():return None
        if self.worker_watch.status()['state']!='exited':raise ValueError('rollback worker exit unqualified')
        if self.result['journal_phase']=='complete' and code!=0:raise ValueError('completed rollback worker failed to exit normally')
        saved=self.journal.read()
        if saved is None or saved['file_sha256']!=self.completed_digest:raise ValueError('completed rollback journal changed')
        return self.result|{'worker_exited':True,'worker_exit_code':code,'journal_file_sha256':self.completed_digest}

    def close(self):
        """Release coordinator resources. NEVER terminate the rollback worker.

        An armed child continues to its original deadline after pipe closure.
        Its durable journal must be inspected if the final report is unavailable.
        Caller must retain source/data and endpoint resources until restoration.
        """
        if self.child is not None:
            for pipe in (self.child.stdin,self.child.stdout):
                if pipe is not None:pipe.close()
            self.child.poll()
        if self.worker_watch is not None:self.worker_watch.close()
        self.journal.close()
